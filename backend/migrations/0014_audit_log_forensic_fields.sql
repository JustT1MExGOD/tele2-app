-- 0014_audit_log_forensic_fields.sql
--
-- 20.10.0 (Audit & Observability 2.0) — org_id на audit_log записывался как
-- "сеть, в разрезе которой произошло действие", но не различал сеть АКТОРА
-- и сеть ЦЕЛИ действия — сегодня они всегда совпадают (все 5 инструментированных
-- действий проходят org-scope проверку до записи в аудит), но для
-- forensic-разбора это два разных факта, которые стоит хранить раздельно
-- с самого начала, не откладывая до первого реального кросс-org кейса.
-- actor_role — роль на момент действия (роль могут сменить позже, и тогда
-- "кем он был, когда это делал" теряется без отдельного снимка).
ALTER TABLE public.audit_log
  ADD COLUMN actor_role text,
  ADD COLUMN target_org_id text;

COMMENT ON COLUMN public.audit_log.target_org_id IS
  'Сеть цели действия — сегодня всегда совпадает с org_id (сетью актора), т.к. все текущие audited-действия org-scoped; разделено на будущее.';
