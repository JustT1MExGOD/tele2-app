-- T2 Miranda — различие между корпоративными аккаунтами точки/кассы
-- (должны быть привязаны ровно к одному устройству за раз) и личными
-- аккаунтами сотрудника (могут работать с нескольких устройств
-- одновременно). По умолчанию false — существующее поведение
-- (неограниченное число активных привязок на аккаунт) не меняется,
-- пока админ явно не отметит аккаунт как device_exclusive.
ALTER TABLE public.corporate_accounts
  ADD COLUMN IF NOT EXISTS device_exclusive boolean NOT NULL DEFAULT false;
