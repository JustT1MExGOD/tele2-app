-- 0005_cron_send_log.sql
--
-- Найдено при разборе бизнес-корректности: ни micro/final отчёты, ни
-- напоминания о завтрашней смене не имели никакой защиты от повторной
-- отправки. Два реальных сценария дублирования: (1) Railway держит старый
-- контейнер живым, пока новый не пройдёт healthcheck (см. 17.5.1) — при
-- деплое ровно в минуту отчёта оба процесса могут независимо тикнуть один
-- и тот же cron-тик и оба отправить фото в чат; (2) есть ручная кнопка
-- «отправить микро-отчёт сейчас» (routes-reports.ts) — менеджер может
-- нажать её в ту же минуту, что и автоматический тик, тоже задваивая
-- фото. Единый ключ на любое отправляемое событие, тот же паттерн
-- claim-по-UNIQUE, что offline_sync_log/client_id (17.9.0).
CREATE TABLE public.cron_send_log (
    id bigserial PRIMARY KEY,
    key text NOT NULL UNIQUE,
    created_at timestamptz DEFAULT now() NOT NULL
);
